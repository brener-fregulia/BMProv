#[test]
fn golden_v1_vector_matches_pinned_literals() {
    assert_eq!(EXPECTED_TRANSCRIPT.len(), 133);
    assert_eq!(EXPECTED_CARRIER.len(), 263);

    let signer = FixtureAssertionSigner::from_seed(SEED);
    assert_eq!(signer.public_key().as_bytes(), EXPECTED_PUBLIC_KEY);

    let boot_nonce = BootNonce::from_bytes(BOOT_NONCE_BYTES);
    let fingerprint = ServerCertFingerprint::from_sha256_digest(FINGERPRINT_BYTES);
    let assertion = signer.sign_v1(boot_nonce, fingerprint);

    assert_eq!(*assertion.transcript_bytes(), EXPECTED_TRANSCRIPT);
    assert_eq!(assertion.signature_bytes(), EXPECTED_SIGNATURE);
    assert_eq!(assertion.site_key_id_bytes(), EXPECTED_SITE_KEY_ID);
    assert_eq!(assertion.to_wire_value(), EXPECTED_CARRIER);

    // The pinned carrier literal parses back to the same assertion, and
    // verifies against the pinned public key.
    let parsed =
        BootstrapAssertion::parse_wire_value(EXPECTED_CARRIER).expect("golden carrier parses");
    assert_eq!(parsed, assertion);

    let accepted = AcceptedSiteKeys::single(signer.public_key());
    let verified = parsed.verify(&accepted).expect("golden vector must verify");
    assert_eq!(*verified.boot_nonce().as_bytes(), BOOT_NONCE_BYTES);
    assert_eq!(*verified.server_fingerprint().as_bytes(), FINGERPRINT_BYTES);
}
